/* ============================================================
 * 运行时配置 —— 改这个文件不用重新构建，刷新即生效。
 *
 * 【品牌】brand 是这个前台自己的名字（顶栏图标、登录页、页脚），
 *   和「站点名」完全是两回事。改这里只影响显示，不影响你连哪个站。
 *
 * 【多站点】sites 是「预置站点清单」，可以同时挂任意多个 NexusPHP 站点：
 *   id        唯一标识（小写字母/数字，改了会让该站令牌失效）
 *   name      顶栏显示名
 *   apiBase   该站的开放 API 根地址（同域填 /api/v1，跨域填完整地址）
 *   color     站点标识色，可选
 *   pushEndpoint / loginEndpoint / coverProxy  可选，按站点独立配置
 *
 * sites 默认留空：第一次打开会进 /login，让你填「标识 / 名称 / API 地址 / 令牌」，
 * 站点只存在访问者本机浏览器里，不会被别人的站名污染。
 * 想让某个站对所有访问者默认出现，再往下面数组里加一条，例如：
 *   { id: 'those', name: 'Those', apiBase: 'https://pt.example.com/api/v1', color: '#2bd9c4' },
 *
 * 令牌【不要写在这里】。每个站点、每个用户各自在 /login 里粘贴自己的令牌，
 * 按站点 id 分别存在访问者本机浏览器里。
 * 也可以在网站里「连接设置 → 站点管理」直接增删改，只存本机、不用改文件。
 *
 * coverProxy 站点级图片代理（格式 {base}?f=0，已有查询串会自动接 &）。
 *            也可以写在**顶层**（与 sites 同级）作为所有站点的默认值，
 *            站点自己配了就用站点的，没配就落到顶层这个。
 *            注意：它必须写在 window.__TEY_API__ = { ... } 对象内部，
 *            写在 }; 后面是无效的（JS 不会报错，但配置读不到）。
 *            同域站点建议直接写相对路径 /img.php?f=0，不受 www / 非 www 影响。
 *            豆瓣类图床需要特定 Referer，公共代理抓不到，交给自建代理最稳。
 *            配好之后前端会自动做两件事：
 *              ① 封面地址拼成 {base}&u=<图片地址> 去取图（防盗链图床直接走代理，不白等直连）
 *              ② 封面缺失 / 图已删时，拼 {base}&q=<片名> 让代理去豆瓣搜一张补上
 *            抓不到时代理会返回 404，前端自动回落到生成式封面。
 *            三种部署方式见 deploy/image-proxy/（Cloudflare Worker / img.php / nginx），
 *            部署后填自己的地址，例如
 *              https://img.those.cc/img?f=0
 *              https://those.cc/img.php?f=0
 *
 * imageMode 图片加载方式：
 *   auto   原图直连 → 站点代理 → 公共代理（默认，逐级回退，能显示真图且不破图）
 *   direct 只直连原图，不经过任何第三方
 *   proxy  只走代理（coverProxy 优先，否则公共图片代理）
 *   off    不加载外链图片，全部用生成式封面
 * ============================================================ */
window.__TEY_API__ = {
  brand: 'Those',
  activeSite: '',
  imageMode: 'auto',
  sites: [],
};
